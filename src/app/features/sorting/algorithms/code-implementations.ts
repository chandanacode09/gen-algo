// ============= BUBBLE SORT =============
export const BUBBLE_SORT_PYTHON = [
  'def bubble_sort(arr):',
  '    n = len(arr)',
  '    ',
  '    for i in range(n - 1):',
  '        swapped = False',
  '        ',
  '        for j in range(0, n - i - 1):',
  '            if arr[j] > arr[j + 1]:',
  '                arr[j], arr[j + 1] = arr[j + 1], arr[j]',
  '                swapped = True',
  '        ',
  '        if not swapped:',
  '            break',
  '    ',
  '    return arr'
];

export const BUBBLE_SORT_JAVA = [
  'public class BubbleSort {',
  '    public static void bubbleSort(int[] arr) {',
  '        int n = arr.length;',
  '        ',
  '        for (int i = 0; i < n - 1; i++) {',
  '            boolean swapped = false;',
  '            ',
  '            for (int j = 0; j < n - i - 1; j++) {',
  '                if (arr[j] > arr[j + 1]) {',
  '                    int temp = arr[j];',
  '                    arr[j] = arr[j + 1];',
  '                    arr[j + 1] = temp;',
  '                    swapped = true;',
  '                }',
  '            }',
  '            ',
  '            if (!swapped) break;',
  '        }',
  '    }',
  '}'
];

// ============= SELECTION SORT =============
export const SELECTION_SORT_PYTHON = [
  'def selection_sort(arr):',
  '    n = len(arr)',
  '    ',
  '    for i in range(n - 1):',
  '        min_idx = i',
  '        ',
  '        for j in range(i + 1, n):',
  '            if arr[j] < arr[min_idx]:',
  '                min_idx = j',
  '        ',
  '        arr[i], arr[min_idx] = arr[min_idx], arr[i]',
  '    ',
  '    return arr'
];

